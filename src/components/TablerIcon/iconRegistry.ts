export type TablerIconComponent = ComponentType<{
  size?: number | string
  stroke?: number | string
  color?: string
  className?: string
}>

/**
 * The finite set of Tabler icons editors can pick and the frontend can render.
 *
 * Deliberately NOT a dynamic import keyed by a variable. TablerIcon used to build
 * its import path from the icon name, and a dynamic import whose path contains a
 * variable forces the bundler to emit a chunk for every file matching the glob —
 * all 6,090 icons — plus a name-to-chunk manifest that lands on the page's
 * initial load. Measured on the homepage: 720,691 -> 525,053 bytes gzip once
 * that import was gone, and the chunk count fell from ~6,000 to 95. See
 * plans/260826-1801-frontend-bundle-and-assets/.
 *
 * IconPicker reads this same map, so an editor cannot select an icon the
 * frontend would then fail to render.
 *
 * Keys are kebab-case because that is what the CMS stores.
 *
 * To add an icon: add its kebab-case name to a group below and the matching
 * IconX to the import above. `pnpm exec tsx scripts/collect-cms-icons.ts --check`
 * verifies every name the CMS holds is present here.
 */
