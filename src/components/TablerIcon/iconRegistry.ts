export type RegisteredIconName = keyof typeof iconRegistry

export const registeredIconNames = Object.keys(iconRegistry).sort()

/** Undefined for an unknown name — callers render nothing rather than throwing. */
export function getRegisteredIcon(name: string): TablerIconComponent | undefined {
  return (iconRegistry as Record<string, TablerIconComponent>)[name]
}
